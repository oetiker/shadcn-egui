//! Markdown report per upstream style: per marker, what did not translate
//! and why.

use crate::resolve::Marker;

pub fn report(style: &str, pin: &str, markers: &[(String, Marker)]) -> String {
    let unsupported: usize = markers.iter().map(|(_, m)| m.unsupported.len()).sum();
    let mut s = format!("# stylegen report: {style}\n\n<!-- generated by tools/stylegen — do not edit -->\n\nUpstream: shadcn-svelte `{pin}`, `style-{style}.css`.\n\n");
    s += &format!(
        "Unsupported classes in shipped markers: **{unsupported}**{}\n\n",
        if unsupported == 0 { " (exportable)" } else { " (not exportable)" }
    );
    for (name, m) in markers {
        if m.unsupported.is_empty() && m.ignored.is_empty() {
            continue;
        }
        s += &format!("## `{name}`\n\n");
        for (c, why) in &m.unsupported {
            s += &format!("- **unsupported** `{c}`: {why}\n");
        }
        for (c, why) in &m.ignored {
            s += &format!("- ignored `{c}`: {why}\n");
        }
        s += "\n";
    }
    s
}
