//! Markdown report per upstream style: per marker, the design corrections
//! applied, and what did not translate and why.

use crate::resolve::Part;

pub fn report(style: &str, pin: &str, parts: &[Part]) -> String {
    let unsupported: usize = parts.iter().map(|p| p.marker.unsupported.len()).sum();
    let mut s = format!("# stylegen report: {style}\n\n<!-- generated by tools/stylegen — do not edit -->\n\nUpstream: shadcn-svelte `{pin}`, `style-{style}.css`.\n\n");
    s += &format!(
        "Unsupported classes in shipped markers: **{unsupported}**{}\n\n",
        if unsupported == 0 {
            " (exportable)"
        } else {
            " (not exportable)"
        }
    );
    for p in parts {
        let (name, m) = (&p.name, &p.marker);
        if m.unsupported.is_empty()
            && m.ignored.is_empty()
            && p.corrections.is_empty()
            && m.routed.is_empty()
        {
            continue;
        }
        s += &format!("## `{name}`\n\n");
        for c in &p.corrections {
            s += &format!("- {c}\n");
        }
        for r in &m.routed {
            s += &format!("- {r}\n");
        }
        for (c, why) in &m.unsupported {
            s += &format!("- **unsupported** `{c}`: {why}\n");
        }
        for (c, why) in &m.ignored {
            s += &format!("- ignored `{c}`: {why}\n");
        }
        s += "\n";
    }
    s
}
